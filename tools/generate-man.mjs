#!/usr/bin/env node
// Generates man/man1/rigorkit.1 from help/*.txt (the single help source, RF-27) and, with --check,
// runs the repository checks for the rigorkit command (RF-28, RF-61):
//   - every command in bin/rigorkit's dispatch has a help file and a line in help/rigorkit.txt, and back;
//   - every install.sh option has a line in help/install.txt "Options:", and back;
//   - the committed manual page equals what the help source generates;
//   - bin/ holds only `rigorkit`.
// Usage: node tools/generate-man.mjs [--root <dir>] [--check]
import { existsSync, readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const MAN = 'man/man1/rigorkit.1';

export function commandsInHelp(root) {
  const text = readFileSync(path.join(root, 'help/rigorkit.txt'), 'utf8');
  return section(text, 'Commands:').map(l => l.match(/^ {2}(\S+)/)?.[1]).filter(Boolean);
}

// Arms of `case $cmd in … esac` in bin/rigorkit; words only (no options, no catch-all).
export function commandsInDispatch(root) {
  const lines = readFileSync(path.join(root, 'bin/rigorkit'), 'utf8').split('\n');
  const start = lines.findIndex(l => /^\s*case \$cmd in\s*$/.test(l));
  if (start < 0) return null;
  const out = [];
  for (const l of lines.slice(start + 1)) {
    if (/^\s*esac\b/.test(l)) break;
    const m = l.match(/^\s*([^)\s][^)]*)\)/);
    if (!m) continue;
    for (const label of m[1].split('|')) if (/^[a-z][a-z0-9-]*$/.test(label)) out.push(label);
  }
  return out;
}

// Arms of the `case "$1" in … esac` option loop in install.sh.
export function optionsInInstaller(root) {
  const lines = readFileSync(path.join(root, 'install.sh'), 'utf8').split('\n');
  const start = lines.findIndex(l => /^\s*case "\$1" in\s*$/.test(l));
  if (start < 0) return null;
  const out = [];
  for (const l of lines.slice(start + 1)) {
    if (/^\s*esac\b/.test(l)) break;
    const m = l.match(/^\s*(-[^)\s]*)\)/);
    if (m) out.push(...m[1].split('|').filter(o => o.startsWith('-')));
  }
  return out;
}

export function optionsInHelp(root, command) {
  const text = readFileSync(path.join(root, 'help', `${command}.txt`), 'utf8');
  const out = [];
  for (const l of section(text, 'Options:')) {
    const m = l.match(/^ {2}(-[\w-]+)(?:, (-[\w-]+))?/);
    if (m) out.push(m[1], ...(m[2] ? [m[2]] : []));
  }
  return out;
}

function section(text, title) {
  const lines = text.split('\n'), i = lines.indexOf(title);
  if (i < 0) return [];
  const out = [];
  for (const l of lines.slice(i + 1)) { if (l === '' || !l.startsWith(' ')) break; out.push(l); }
  return out;
}

const esc = line => (/^[.']/.test(line) ? '\\&' : '') + line.replace(/\\/g, '\\e').replace(/-/g, '\\-');
const block = text => ['.nf', ...text.replace(/\n+$/, '').split('\n').map(esc), '.fi'];

export function renderMan(root) {
  const read = name => readFileSync(path.join(root, 'help', `${name}.txt`), 'utf8');
  const out = [
    '.\\" Generated by tools/generate-man.mjs from help/*.txt. Do not edit.',
    '.TH RIGORKIT 1 "" "rigorkit" "rigorkit manual"',
    '.SH NAME', 'rigorkit \\- install rigorkit packs and run its helper scripts',
    '.SH SYNOPSIS', ...block(read('rigorkit')),
  ];
  for (const c of commandsInHelp(root)) out.push(`.SH ${esc(c.toUpperCase())}`, ...block(read(c)));
  return out.join('\n') + '\n';
}

export function check(root) {
  const problems = [];
  const helpCommands = commandsInHelp(root), dispatch = commandsInDispatch(root);
  if (!dispatch) problems.push('bin/rigorkit: dispatch "case $cmd in" not found');
  else {
    for (const c of dispatch) {
      if (!helpCommands.includes(c)) problems.push(`command without help in help/rigorkit.txt: ${c}`);
      if (!existsSync(path.join(root, 'help', `${c}.txt`))) problems.push(`command without help file help/${c}.txt: ${c}`);
    }
    for (const c of helpCommands) if (!dispatch.includes(c)) problems.push(`help names a command that does not exist: ${c}`);
  }
  const installed = optionsInInstaller(root), documented = optionsInHelp(root, 'install');
  if (!installed) problems.push('install.sh: option loop "case \\"$1\\" in" not found');
  else {
    for (const o of installed) if (!documented.includes(o)) problems.push(`install option without help in help/install.txt: ${o}`);
    for (const o of documented) if (!installed.includes(o)) problems.push(`help/install.txt names an option install.sh does not have: ${o}`);
  }
  const man = path.join(root, MAN);
  if (!existsSync(man) || readFileSync(man, 'utf8') !== renderMan(root)) problems.push(`${MAN} differs from help/*.txt: run node tools/generate-man.mjs`);
  const binDir = path.join(root, 'bin');
  for (const f of existsSync(binDir) ? readdirSync(binDir).filter(f => f !== 'rigorkit') : []) problems.push(`bin/${f}: bin/ must hold only rigorkit`);
  return problems;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  let root = fileURLToPath(new URL('..', import.meta.url)), mode = 'write';
  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--root') root = path.resolve(args[++i] ?? '');
    else if (args[i] === '--check') mode = 'check';
    else { console.error(`generate-man: unknown argument: ${args[i]}`); process.exit(2); }
  }
  if (mode === 'check') {
    const problems = check(root);
    if (problems.length) { for (const p of problems) console.error(`FAIL ${p}`); process.exit(1); }
    console.log('cli checks: PASS');
  } else {
    mkdirSync(path.join(root, 'man/man1'), { recursive: true });
    writeFileSync(path.join(root, MAN), renderMan(root));
    console.log(`wrote ${MAN}`);
  }
}
